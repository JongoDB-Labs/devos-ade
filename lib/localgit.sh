# shellcheck shell=bash
# The built-in local git server: Forgejo (the community fork of Gitea; JON-810), a stack service with a web UI at
# git.PORTAL_HOST (GIT_HOST), so projects can push, pull and manage git — branches, pull requests — on this computer,
# with no GitHub or off-site GitLab. On by default and light (one container, SQLite, about 110 MB at rest); LOCALGIT=off
# (Settings › Claude Code › Local git server, or ./stack config set LOCALGIT off) removes the container — its repositories
# stay in the gitdata volume. ./stack uninstall removes them with the rest.
#
#   compose.yaml            forgejo (profile "forgejo": in ./stack's calls while LOCALGIT is not off), on the internal
#                           "localgit" network — Caddy and the terminal's gateway share it, nothing else: no way out to the
#                           internet (a mirror's way out is added only while one is set up)
#   caddy/localgit-on.caddy the web UI behind the portal's session (Forgejo's own sign-in: the owner's account below)
#   compose.localgit.yaml   with the terminal: the gateway listens on https://gateway:8093 too — the sandbox's git host
#                           (caddy/localgit-gateway-on.caddy: git's smart HTTP paths of a repository to Forgejo, nothing
#                           else), reachable with TERMINAL_EGRESS=internet, host and off alike: an egress carve-out in the
#                           way LiteLLM's paths are, never the internet
#   TLS                     .state/localgit/tls: a certificate ./stack makes for the name "gateway" (EC P-256, ten years),
#                           mounted read-only into the gateway; the code container hands it to the sandbox's git as the one CA
#                           trusted for that host (a Git host of the Code page, "Local git server")
#   the owner's account     "devos", a site admin made here (LOCALGIT_ADMIN_PASSWORD in .env, generated by setup; Forgejo's
#                           sign-in until the portal signs you in); the Code page's host holds a token of that account
#                           scoped to repositories only (write:repository, read:user) — never in .env, the portal or a backup
#
# Hooks for the rest of ./stack:
#   localgit_on / localgit_services   lib/commands.sh optional_services (./stack up's list; status, logs, restart)
#   localgit_overlay_wanted           lib/common.sh compose_overlays (compose.localgit.yaml)
#   localgit_tls_ensure               the certificate, before any compose call that mounts it
#   localgit_secrets / localgit_start / localgit_up / localgit_remove / localgit_after_up
#                     setup, ./stack up, ./stack config, code enable: the secret and certificate, the container, Caddy and the
#                     gateway where the switch changed them, the account, the Code page's host
#   localgit_status_line / localgit_summary_line   ./stack status, setup's summary

LOCALGIT_USER=devos
LOCALGIT_GATEWAY_HOST=gateway
LOCALGIT_GATEWAY_PORT=8093
LOCALGIT_TOKEN_SCOPES="write:repository,read:user"

# (localgit_on, localgit_overlay_wanted, localgit_tls_dir and localgit_tls_ensure are lib/common.sh's: compose_overlays and dc
# need them wherever only that file is loaded)
# localgit_services -> "forgejo" while it is on (lib/commands.sh optional_services)
localgit_services() { ! localgit_on || echo forgejo; }

# localgit_secrets — the owner's account password (never printed), and the switch's default
localgit_secrets() {
  ensure_env LOCALGIT "on"
  ensure_env LOCALGIT_ADMIN_PASSWORD "Lg9-$(gen_hex 14)"
}

# (the shell's own quoting below is on purpose: the container's sh expands $1, $LG_PW and $LG_EMAIL, never this shell)
# _lg_forgejo ARGS… -> the forgejo CLI in its container (as its own user; its settings are the container's environment)
_lg_forgejo() { dc exec -T forgejo forgejo "$@"; }
# _lg_running -> 0 while the container runs and answers its health check
_lg_running() { [ -n "$(dc ps -q --status running forgejo 2>/dev/null | head -n 1)" ] && dc exec -T forgejo curl -fsS http://127.0.0.1:3000/api/healthz >/dev/null 2>&1; }

# localgit_ensure_admin -> the owner's account is there, a site admin with .env's password (set again each time: .env
# decides). The password goes in the environment of the one command, never on a command line (ps shows those).
localgit_ensure_admin() {
  local pw email users
  pw="$(get_env LOCALGIT_ADMIN_PASSWORD)"; [ -n "$pw" ] || return 1
  email="$(get_env OPENWEBUI_ADMIN_EMAIL)"; [ -n "$email" ] || email="$LOCALGIT_USER@$(portal_host)"
  users="$(_lg_forgejo admin user list 2>/dev/null)" || return 1
  if printf '%s\n' "$users" | awk -v u="$LOCALGIT_USER" 'NR > 1 && $2 == u { f = 1 } END { exit !f }'; then
    # shellcheck disable=SC2016  # (expanded by the container's sh)
    LG_PW="$pw" dc exec -T -e LG_PW forgejo sh -c 'forgejo admin user change-password --username "$1" --password "$LG_PW" --must-change-password=false' sh "$LOCALGIT_USER" >/dev/null 2>&1
  else
    # shellcheck disable=SC2016  # (expanded by the container's sh)
    LG_PW="$pw" LG_EMAIL="$email" dc exec -T -e LG_PW -e LG_EMAIL forgejo sh -c \
      'forgejo admin user create --admin --username "$1" --email "$LG_EMAIL" --password "$LG_PW" --must-change-password=false' sh "$LOCALGIT_USER" >/dev/null 2>&1
  fi
}

# _lg_send JSON -> 0 and the answer line in _LG_ANSWER: the code container's import (server/import-host.mjs, JSON on stdin:
# never on a command line, in an environment variable or a file); never fatal
_LG_ANSWER=''
_lg_send() {
  _LG_ANSWER="$(printf '%s' "$1" | dc exec -T code node server/import-host.mjs 2>/dev/null | grep '^{"ok":' | tail -n 1)" || true
  case "$_LG_ANSWER" in '{"ok":true'*) return 0 ;; esac
  return 1
}
_lg_json_str() { local v="$1"; v="${v//\\/\\\\}"; v="${v//\"/\\\"}"; v="${v//$'\n'/\\n}"; printf '"%s"' "$v"; }

# localgit_register_host -> the Code page has the built-in git server as a Git host with this certificate as its CA, and a token
# of the owner's account scoped to repositories. The CA first (the host there already: kept in step, its token left alone);
# "no token" says the host is new: a token is made then (Forgejo's own command, printed once) and handed over the same way.
# Quiet and never fatal: where there is no Code page, or no sign of the container yet, nothing is registered and the next
# ./stack up tries again.
localgit_register_host() {
  local ca tok msg
  code_ready || return 0
  [ -n "$(dc ps -q --status running code 2>/dev/null | head -n 1)" ] || return 0
  localgit_tls_ensure || return 1
  ca="$(cat "$(localgit_tls_dir)/tls.crt")" || return 1
  msg="{\"source\":\"localgit\",\"ca\":$(_lg_json_str "$ca"),\"account\":\"$LOCALGIT_USER\"}"
  if _lg_send "$msg"; then return 0; fi
  case "$_LG_ANSWER" in *'"no token"'*) ;; *) return 1 ;; esac
  tok="$(_lg_forgejo admin user generate-access-token --username "$LOCALGIT_USER" --token-name "devos-ade-code-$(date +%s)" \
    --scopes "$LOCALGIT_TOKEN_SCOPES" --raw 2>/dev/null | tail -n 1 | tr -d '\r')" || tok=''
  [ -n "$tok" ] || return 1
  msg="{\"source\":\"localgit\",\"ca\":$(_lg_json_str "$ca"),\"account\":\"$LOCALGIT_USER\",\"token\":$(_lg_json_str "$tok")}"
  tok=''
  _lg_send "$msg"; msg=''
}

# localgit_after_up — setup, ./stack up, code enable, ./stack config: the account and the Code page's host, once the container
# is healthy. Never fatal (a warning says what to do).
localgit_after_up() {
  localgit_on || return 0
  localgit_secrets
  _lg_running || { warn "the built-in git server is not running — ./stack logs forgejo says why (./stack up tries again)"; return 0; }
  localgit_ensure_admin || { warn "could not make the git server's owner account — ./stack logs forgejo"; return 0; }
  localgit_register_host || { code_ready && warn "could not connect the Code page to the built-in git server — ./stack up tries again"; }
  return 0
}

# localgit_start — setup, ./stack up and the switch: its secret and certificate, then on: the container started and healthy;
# off: removed (never touching Caddy or the gateway: setup and up bring them up with their new configuration themselves).
# Home's record of the containers follows (services_status_write). Never fatal: a container that does not start is said.
localgit_start() {
  if ! localgit_on; then localgit_remove; services_status_write; return 0; fi
  localgit_secrets
  localgit_tls_ensure || warn "the git server's certificate could not be made (openssl): the sandbox cannot reach it until ./stack up"
  run_phase "Local git server (Forgejo)" forgejo dc up -d --no-deps --wait forgejo ||
    warn "the built-in git server did not start — ./stack logs forgejo says why (Git hosts has no local server until it does)"
  services_status_write
  return 0
}

# localgit_up — ./stack config and Settings' switch: localgit_start, then Caddy and the terminal's gateway where their
# configuration changed with the switch (the site, the listener: compose recreates just those two, a few seconds), the owner
# account and the Code page's host. Never fatal.
localgit_up() {
  localgit_start
  localgit_on || { localgit_recreate_fronts; return 0; }
  localgit_recreate_fronts
  localgit_after_up
  services_status_write
  return 0
}

# localgit_recreate_fronts — Caddy and the terminal's gateway recreated where the git server's site and listener changed
localgit_recreate_fronts() {
  local s=caddy
  ! terminal_ready || s="$s terminal-gateway"
  # shellcheck disable=SC2086  # a word a service
  up_services --no-deps $s >/dev/null 2>&1 || warn "Caddy or the terminal's gateway did not restart for the git server — ./stack up"
  ensure_portal_reachable
}

# localgit_remove — the container removed (named with its profile on: off, compose would not see it); the gitdata volume
# stays. Only when there is one; never fatal.
localgit_remove() {
  [ -n "$(_LG_PROFILE=1 dc ps -aq forgejo 2>/dev/null)" ] || return 0
  _LG_PROFILE=1 dc rm -sf forgejo >/dev/null 2>&1 || warn "could not remove the git server's container — ./stack down removes it"
}

# localgit_rollback_cleanup — ./stack rollback to a version without it: the container removed by its Compose labels (the
# repositories' volume stays; the network goes after the up, lib/rollback.sh)
localgit_rollback_cleanup() {
  local p ids
  p="$(project_name)"
  ids="$(docker ps -aq --filter "label=com.docker.compose.project=$p" --filter "label=com.docker.compose.service=forgejo" 2>/dev/null || true)"
  # shellcheck disable=SC2086  # one id per word
  [ -z "$ids" ] || docker rm -f $ids >/dev/null 2>&1 || warn "could not remove the git server's container — remove it with: docker rm -f $p-forgejo-1"
}

# localgit_uninstall_cleanup — ./stack uninstall: the repositories' volume (and its network) removed even while the server is off
# (its profile is not on then: `dc down -v` would not see them). Never fatal.
localgit_uninstall_cleanup() {
  local p; p="$(project_name)"
  _LG_PROFILE=1 dc rm -sfv forgejo >/dev/null 2>&1 || true
  docker volume rm "${p}_gitdata" >/dev/null 2>&1 || true
  docker network rm "${p}_localgit" >/dev/null 2>&1 || true
}

# localgit_web_url -> the server's web address (http://git.PORTAL_HOST[:port])
localgit_web_url() { portal_url git; }

localgit_status_line() {
  if localgit_on; then
    printf '  Git server on (Forgejo): %s — sign in as %s (password: LOCALGIT_ADMIN_PASSWORD in .env); the Code page'"'"'s sandbox clones and pushes\n' "$(localgit_web_url)" "$LOCALGIT_USER"
    printf '             with https://%s:%s/%s/REPO.git (Git hosts: Local git server; a push creates a missing repository, private)\n' "$LOCALGIT_GATEWAY_HOST" "$LOCALGIT_GATEWAY_PORT" "$LOCALGIT_USER"
  else
    printf '  Git server off (LOCALGIT=off): ./stack config set LOCALGIT on turns the built-in git server on — its repositories stay in the gitdata volume\n'
  fi
}
localgit_summary_line() {
  localgit_on || return 0
  printf '  Git        %s (the built-in git server: repositories on this computer; sign in as %s)\n' "$(localgit_web_url)" "$LOCALGIT_USER"
}

# --- mirroring: ./stack git-server mirror … (code/server/mirrors.mjs, run in the code container: it holds the connected git
# hosts' credentials and reaches the git server through Caddy's internal :8099 site) ---
# Forgejo's own repository mirroring: a push mirror keeps a GitHub / GitLab copy of a local repository up to date (the local
# one is the source; the remote's refs are force-updated), a pull mirror keeps a read-only local copy of a remote. Off until
# one is made: the git server has no way out to the internet at all until then. While a mirror exists it gets a network of its
# own (localgit-out, compose.localgit-mirror.yaml) and Forgejo may reach only the mirrors' host names (its [migrations]
# ALLOWED_DOMAINS, never this computer's own addresses or your network: its own refusal of private addresses stays on).
# LOCALGIT_MIRROR_EGRESS / LOCALGIT_MIRROR_HOSTS in .env are ./stack's record of that, rewritten from what the server really
# has (localgit_mirror_reconcile) — never edited by hand.

localgit_mirror_usage() {
  cat <<'EOT'
Usage: ./stack git-server status
       ./stack git-server mirror list
       ./stack git-server mirror add push|pull REPO REMOTE_URL [--interval 8h] [--no-sync-on-commit] [--yes]
       ./stack git-server mirror sync REPO [--pull]
       ./stack git-server mirror remove REPO NAME
       ./stack git-server mirror reconcile

  The built-in git server (Forgejo) mirrors to the git hosts you connected in the Code page (Git hosts), with an
  access token for the remote (a sign-in cannot be used: its token lasts hours and cannot be renewed inside Forgejo).
  REPO is a repository of the owner on the built-in server (a push creates it); REMOTE_URL an https:// URL of a
  connected host.
    push   REPO is the source and the remote a copy: every push to REPO here, and every INTERVAL, Forgejo pushes ALL its
           branches and tags and FORCE-UPDATES the remote's — what is only there is overwritten. The remote repository
           must exist (empty is fine). A normal remote you fetch from and push to is a different thing: use the Git panel.
    pull   a new private repository REPO, a read-only copy of the remote that Forgejo fetches every INTERVAL.
  The token is handed to Forgejo, which keeps it (encrypted with its own secret, in the gitdata volume) because it pushes
  and fetches on its own later. Until a mirror exists the git server has no network to the internet; while one does it
  has one of its own, limited to the mirrors' host names. You confirm first (--yes: without asking). Only on the computer
  running DevOS ADE, with the Code page running. Status (last sync, last error): this list, the Code page's Git hosts
  dialog, and the repository's Settings › Mirror settings in the git server's web UI.
EOT
}

# _lg_code_ready -> the Code page's container runs (it keeps Git hosts and makes the mirrors), else why not
_lg_code_ready() {
  localgit_on || die "the built-in git server is off (LOCALGIT=off): ./stack config set LOCALGIT on turns it on"
  code_on || die "the Code page is off: ./stack code enable turns it on (the connected git hosts are its)"
  code_ready || die "the Code page is left out: the browser terminal it runs in is off or not ready (./stack code status)"
  [ -n "$(dc ps -q --status running code 2>/dev/null | head -n 1)" ] || die "the Code page's container is not running: ./stack up"
  _lg_running || die "the built-in git server is not running: ./stack up (./stack logs forgejo)"
}

# _lg_mirror_op JSON -> 0 and the answer line in _LG_ANSWER; the request goes on stdin (nothing secret in it)
_lg_mirror_op() {
  _LG_ANSWER="$(printf '%s' "$1" | dc exec -T code node server/mirror-host.mjs 2>/dev/null | grep '^{"ok":' | tail -n 1)" || true
  case "$_LG_ANSWER" in '{"ok":true'*) return 0 ;; esac
  return 1
}
# _lg_op_error -> the error text of the last answer
_lg_op_error() {
  local e; e="$(printf '%s' "$_LG_ANSWER" | sed -n 's/.*"error":"\([^"]*\)".*/\1/p')"
  case "$_LG_ANSWER" in '') echo "the Code page's container did not answer (./stack code status; ./stack logs code)" ;; *) echo "${e:-it failed}" ;; esac
}
# _lg_hosts_csv -> the host names of the mirrors there are (from the server itself), comma separated; fails if it cannot ask
_lg_hosts_csv() {
  _lg_mirror_op '{"op":"hosts"}' || return 1
  printf '%s' "$_LG_ANSWER" | sed -n 's/.*"hosts":\[\([^]]*\)\].*/\1/p' | tr -d '"'
}

# _lg_mirror_egress_apply HOSTS_CSV -> .env's record and Forgejo's way out follow (blank: no mirror, no way out): the container is
# recreated when its networks or its allowed names change (a few seconds), and nothing is done when they did not
_lg_mirror_egress_apply() {
  local hosts="$1" now_hosts now_on want=off
  now_hosts="$(get_env LOCALGIT_MIRROR_HOSTS)"; now_on="$(get_env LOCALGIT_MIRROR_EGRESS)"
  [ -z "$hosts" ] || want=on
  if [ "$want" = "${now_on:-off}" ] && [ "$hosts" = "$now_hosts" ]; then return 0; fi
  set_env LOCALGIT_MIRROR_HOSTS "$hosts"; set_env LOCALGIT_MIRROR_EGRESS "$want"
  if [ "$want" = on ]; then log "the git server gets a way out to $hosts only (while a mirror exists)"
  else log "no mirror is left: the git server has no way out to the internet again"; fi
  run_phase "Local git server (its way out: $want)" forgejo dc up -d --no-deps --wait forgejo || return 1
  services_status_write
}

# localgit_mirror_reconcile — ./stack up, mirror changes: the way out matches the mirrors the server has. Asked of the server
# (through the Code page's container); when that cannot be asked, nothing changes. Never fatal.
localgit_mirror_reconcile() {
  local hosts
  localgit_on || return 0
  code_ready && [ -n "$(dc ps -q --status running code 2>/dev/null | head -n 1)" ] || return 0
  _lg_running || return 0
  hosts="$(_lg_hosts_csv)" || return 0
  _lg_mirror_egress_apply "$hosts" || warn "the git server's way out could not be changed — ./stack logs forgejo"
  return 0
}

cmd_git_server() {
  local sub="${1:-}"; [ $# -eq 0 ] || shift
  case "$sub" in
    status) localgit_status_line; ! flag_on "$(get_env LOCALGIT_MIRROR_EGRESS)" || printf '  Mirrors    a way out exists for: %s\n' "$(get_env LOCALGIT_MIRROR_HOSTS)" ;;
    mirror) localgit_mirror_cmd "$@" ;;
    '' | help | -h | --help) localgit_mirror_usage ;;
    *) localgit_mirror_usage >&2; die "unknown: ./stack git-server $sub" ;;
  esac
}

localgit_mirror_cmd() {
  local act="${1:-}"; [ $# -eq 0 ] || shift
  case "$act" in
    list) _lg_code_ready; localgit_mirror_list ;;
    add) localgit_mirror_add "$@" ;;
    sync) localgit_mirror_sync "$@" ;;
    remove) localgit_mirror_remove "$@" ;;
    reconcile) _lg_code_ready; localgit_mirror_reconcile ;;
    '' | help | -h | --help) localgit_mirror_usage ;;
    *) localgit_mirror_usage >&2; die "unknown: ./stack git-server mirror $act" ;;
  esac
}

# localgit_mirror_list -> one line per mirror: direction, repository, remote, interval, last sync, last error
localgit_mirror_list() {
  _lg_mirror_op '{"op":"list"}' || die "could not list the mirrors: $(_lg_op_error)"
  python3 -I -c '
import json, sys
d = json.loads(sys.argv[1])
ms = d.get("mirrors", [])
if not ms:
    print("  No mirrors. ./stack git-server mirror add push|pull REPO REMOTE_URL makes one (./stack git-server --help).")
for m in ms:
    kind = "push (the remote is a copy: its refs are force-updated)" if m["direction"] == "push" else "pull (read-only copy of the remote)"
    print("  %-5s %s  <->  %s" % (m["direction"], m["repo"], m["remote"]))
    print("        %s; every %s%s" % (kind, m["interval"], ", and on every push here" if m.get("syncOnCommit") else ""))
    print("        last sync: %s%s" % (m["lastSync"] or "never", ("; last error: " + m["lastError"]) if m.get("lastError") else ""))
    if m.get("name"):
        print("        name: %s (./stack git-server mirror remove %s %s)" % (m["name"], m["repo"].split("/")[-1], m["name"]))
' "$(printf '%s' "$_LG_ANSWER")" 2>/dev/null || printf '%s\n' "$_LG_ANSWER"
}

# _lg_remote_host URL -> the host name of an https:// URL (nothing for another)
_lg_remote_host() {
  local u="$1" h
  case "$u" in https://*) ;; *) return 1 ;; esac
  h="${u#https://}"; h="${h%%/*}"; h="${h%%:*}"; h="${h##*@}"
  _gh_host_ok "$h" || return 1
  printf '%s\n' "$h"
}

localgit_mirror_add() {
  { set +x; } 2>/dev/null
  local dir="${1:-}" repo="${2:-}" url="${3:-}" interval='' sync=true host cur json own=1
  [ $# -ge 3 ] || { localgit_mirror_usage >&2; die "usage: ./stack git-server mirror add push|pull REPO REMOTE_URL"; }
  shift 3
  case "$dir" in push | pull) ;; *) die "push or pull (./stack git-server --help)" ;; esac
  while [ $# -gt 0 ]; do
    case "$1" in
      --interval) [ $# -ge 2 ] || die "--interval needs a value (8h, 30m)"; interval="$2"; shift 2 ;;
      --interval=*) interval="${1#--interval=}"; shift ;;
      --no-sync-on-commit) sync=false; shift ;;
      *) localgit_mirror_usage >&2; die "unknown: $1" ;;
    esac
  done
  host="$(_lg_remote_host "$url")" || die "the remote must be an https:// URL of a connected git host (https://github.com/owner/repo)"
  case "$repo" in '' | *[!A-Za-z0-9._-]* | -*) die "REPO: the repository's name on the built-in server (letters, digits, . _ -)" ;; esac
  case "$interval" in '' | [1-9]*[mh] | 0) ;; *) die "--interval: 10m to 999h (8h, 30m), or 0 for a push mirror that pushes only when something is pushed here" ;; esac
  _lg_code_ready
  cur="$(_lg_hosts_csv)" || die "could not ask the git server which mirrors it has: $(_lg_op_error)"
  case ",$cur," in *",$host,"*) ;; *) cur="${cur:+$cur,}$host" ;; esac
  printf '\nMirror %s: %s  %s  %s?\n' "$dir" "$repo" "$([ "$dir" = push ] && echo '->' || echo '<-')" "$url"
  if [ "$dir" = push ]; then
    printf '  The local repository is the source. On every push to it here%s, Forgejo pushes ALL its branches and tags to\n' "${interval:+ and every $interval}"
    printf '  the remote and FORCE-UPDATES the remote'"'"'s refs: anything that is only there is overwritten. Not a normal remote.\n'
  else
    printf '  A new PRIVATE repository %s on the built-in server: a read-only copy of the remote, fetched every %s.\n' "$repo" "${interval:-8h}"
  fi
  printf '  The connected host'"'"'s access token for %s is handed to Forgejo, which keeps it (encrypted with its own secret, in the\n' "$host"
  printf '  gitdata volume) to do this on its own later. For as long as a mirror exists the git server gets a network of its own\n'
  printf '  to the internet, limited to: %s.\n\n' "${cur//,/, }"
  _githost_confirm "Make it?" || { printf 'No mirror made.\n'; return 1; }
  ! stack_lock_ours || own=0
  stack_lock git-server
  # the way out first (its allowed names must hold the remote's before Forgejo checks the address), the mirror then; a mirror
  # that was not made leaves the way out as the mirrors that exist need it
  if ! _lg_mirror_egress_apply "$cur"; then
    localgit_mirror_reconcile; [ "$own" = 0 ] || stack_unlock; die "the git server could not get its way out — ./stack logs forgejo"
  fi
  json="{\"op\":\"add\",\"direction\":\"$dir\",\"repo\":$(_lg_json_str "$repo"),\"remote\":$(_lg_json_str "$url"),\"syncOnCommit\":$sync${interval:+,\"interval\":\"$interval\"}}"
  if ! _lg_mirror_op "$json"; then
    local why; why="$(_lg_op_error)"
    localgit_mirror_reconcile; [ "$own" = 0 ] || stack_unlock
    die "no mirror made: $why"
  fi
  [ "$own" = 0 ] || stack_unlock
  printf 'Mirror made: %s %s. ./stack git-server mirror list shows its last sync.\n' "$dir" "$repo"
  if [ "$dir" = push ]; then _lg_mirror_op "{\"op\":\"sync\",\"repo\":$(_lg_json_str "$repo")}" >/dev/null 2>&1 && printf 'A first push to the remote was asked for.\n' || true; fi
}

localgit_mirror_sync() {
  local repo="${1:-}" dir=push; [ $# -eq 0 ] || shift
  [ "${1:-}" != --pull ] || dir=pull
  case "$repo" in '' | *[!A-Za-z0-9._-]* | -*) die "usage: ./stack git-server mirror sync REPO [--pull]" ;; esac
  _lg_code_ready
  _lg_mirror_op "{\"op\":\"sync\",\"repo\":$(_lg_json_str "$repo"),\"direction\":\"$dir\"}" || die "not synced: $(_lg_op_error)"
  printf 'A %s sync of %s was asked for: ./stack git-server mirror list shows when it is done.\n' "$dir" "$repo"
}

localgit_mirror_remove() {
  local repo="${1:-}" name="${2:-}" own=1
  case "$repo$name" in '' | *[!A-Za-z0-9._-]*) die "usage: ./stack git-server mirror remove REPO NAME (the name: ./stack git-server mirror list)" ;; esac
  [ -n "$repo" ] && [ -n "$name" ] || die "usage: ./stack git-server mirror remove REPO NAME"
  _lg_code_ready
  ! stack_lock_ours || own=0
  stack_lock git-server
  _lg_mirror_op "{\"op\":\"remove\",\"repo\":$(_lg_json_str "$repo"),\"name\":$(_lg_json_str "$name")}" || { [ "$own" = 0 ] || stack_unlock; die "not removed: $(_lg_op_error)"; }
  localgit_mirror_reconcile
  [ "$own" = 0 ] || stack_unlock
  printf 'Mirror %s of %s removed (the remote repository is untouched; Forgejo forgot the token).\n' "$name" "$repo"
}
