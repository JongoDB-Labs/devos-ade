# shellcheck shell=bash
# The built-in local git server: Forgejo (the community fork of Gitea; JON-810), a stack service with a web UI at
# git.PORTAL_HOST (GIT_HOST), so projects can push, pull and manage git — branches, pull requests — on this computer,
# with no GitHub or off-site GitLab. On by default and light (one container, SQLite, about 110 MB at rest); LOCALGIT=off
# (Settings › Claude Code › Local git server, or ./stack config set LOCALGIT off) removes the container — its repositories
# stay in the gitdata volume. ./stack uninstall removes them with the rest.
#
#   compose.yaml            forgejo (profile "forgejo": in ./stack's calls while LOCALGIT is not off), on the internal
#                           "localgit" network — Caddy and the terminal's gateway share it, nothing else: no way out to the
#                           internet (a mirror's way out is added only while one is set up)
#   caddy/localgit-on.caddy the web UI behind the portal's session (Forgejo's own sign-in: the owner's account below)
#   compose.localgit.yaml   with the terminal: the gateway listens on https://gateway:8093 too — the sandbox's git host
#                           (caddy/localgit-gateway-on.caddy: git's smart HTTP paths of a repository to Forgejo, nothing
#                           else), reachable with TERMINAL_EGRESS=internet, host and off alike: an egress carve-out in the
#                           way LiteLLM's paths are, never the internet
#   TLS                     .state/localgit/tls: a certificate ./stack makes for the name "gateway" (EC P-256, ten years),
#                           mounted read-only into the gateway; the code container hands it to the sandbox's git as the one CA
#                           trusted for that host (a Git host of the Code page, "Local git server")
#   the owner's account     "devos", a site admin made here (LOCALGIT_ADMIN_PASSWORD in .env, generated by setup; Forgejo's
#                           sign-in until the portal signs you in); the Code page's host holds a token of that account
#                           scoped to repositories only (write:repository, read:user) — never in .env, the portal or a backup
#
# Hooks for the rest of ./stack:
#   localgit_on / localgit_services   lib/commands.sh optional_services (./stack up's list; status, logs, restart)
#   localgit_overlay_wanted           lib/common.sh compose_overlays (compose.localgit.yaml)
#   localgit_tls_ensure               the certificate, before any compose call that mounts it
#   localgit_secrets / localgit_start / localgit_up / localgit_remove / localgit_after_up
#                     setup, ./stack up, ./stack config, code enable: the secret and certificate, the container, Caddy and the
#                     gateway where the switch changed them, the account, the Code page's host
#   localgit_status_line / localgit_summary_line   ./stack status, setup's summary

LOCALGIT_USER=devos
LOCALGIT_GATEWAY_HOST=gateway
LOCALGIT_GATEWAY_PORT=8093
LOCALGIT_TOKEN_SCOPES="write:repository,read:user"

# (localgit_on, localgit_overlay_wanted, localgit_tls_dir and localgit_tls_ensure are lib/common.sh's: compose_overlays and dc
# need them wherever only that file is loaded)
# localgit_services -> "forgejo" while it is on (lib/commands.sh optional_services)
localgit_services() { ! localgit_on || echo forgejo; }

# localgit_secrets — the owner's account password (never printed), and the switch's default
localgit_secrets() {
  ensure_env LOCALGIT "on"
  ensure_env LOCALGIT_ADMIN_PASSWORD "Lg9-$(gen_hex 14)"
}

# (the shell's own quoting below is on purpose: the container's sh expands $1, $LG_PW and $LG_EMAIL, never this shell)
# _lg_forgejo ARGS… -> the forgejo CLI in its container (as its own user; its settings are the container's environment)
_lg_forgejo() { dc exec -T forgejo forgejo "$@"; }
# _lg_running -> 0 while the container runs and answers its health check
_lg_running() { [ -n "$(dc ps -q --status running forgejo 2>/dev/null | head -n 1)" ] && dc exec -T forgejo curl -fsS http://127.0.0.1:3000/api/healthz >/dev/null 2>&1; }

# localgit_ensure_admin -> the owner's account is there, a site admin with .env's password (set again each time: .env
# decides). The password goes in the environment of the one command, never on a command line (ps shows those).
localgit_ensure_admin() {
  local pw email users
  pw="$(get_env LOCALGIT_ADMIN_PASSWORD)"; [ -n "$pw" ] || return 1
  email="$(get_env OPENWEBUI_ADMIN_EMAIL)"; [ -n "$email" ] || email="$LOCALGIT_USER@$(portal_host)"
  users="$(_lg_forgejo admin user list 2>/dev/null)" || return 1
  if printf '%s\n' "$users" | awk -v u="$LOCALGIT_USER" 'NR > 1 && $2 == u { f = 1 } END { exit !f }'; then
    # shellcheck disable=SC2016  # (expanded by the container's sh)
    LG_PW="$pw" dc exec -T -e LG_PW forgejo sh -c 'forgejo admin user change-password --username "$1" --password "$LG_PW" --must-change-password=false' sh "$LOCALGIT_USER" >/dev/null 2>&1
  else
    # shellcheck disable=SC2016  # (expanded by the container's sh)
    LG_PW="$pw" LG_EMAIL="$email" dc exec -T -e LG_PW -e LG_EMAIL forgejo sh -c \
      'forgejo admin user create --admin --username "$1" --email "$LG_EMAIL" --password "$LG_PW" --must-change-password=false' sh "$LOCALGIT_USER" >/dev/null 2>&1
  fi
}

# _lg_send JSON -> 0 and the answer line in _LG_ANSWER: the code container's import (server/import-host.mjs, JSON on stdin:
# never on a command line, in an environment variable or a file); never fatal
_LG_ANSWER=''
_lg_send() {
  _LG_ANSWER="$(printf '%s' "$1" | dc exec -T code node server/import-host.mjs 2>/dev/null | grep '^{"ok":' | tail -n 1)" || true
  case "$_LG_ANSWER" in '{"ok":true'*) return 0 ;; esac
  return 1
}
_lg_json_str() { local v="$1"; v="${v//\\/\\\\}"; v="${v//\"/\\\"}"; v="${v//$'\n'/\\n}"; printf '"%s"' "$v"; }

# localgit_register_host -> the Code page has the built-in git server as a Git host with this certificate as its CA, and a token
# of the owner's account scoped to repositories. The CA first (the host there already: kept in step, its token left alone);
# "no token" says the host is new: a token is made then (Forgejo's own command, printed once) and handed over the same way.
# Quiet and never fatal: where there is no Code page, or no sign of the container yet, nothing is registered and the next
# ./stack up tries again.
localgit_register_host() {
  local ca tok msg
  code_ready || return 0
  [ -n "$(dc ps -q --status running code 2>/dev/null | head -n 1)" ] || return 0
  localgit_tls_ensure || return 1
  ca="$(cat "$(localgit_tls_dir)/tls.crt")" || return 1
  msg="{\"source\":\"localgit\",\"ca\":$(_lg_json_str "$ca"),\"account\":\"$LOCALGIT_USER\"}"
  if _lg_send "$msg"; then return 0; fi
  case "$_LG_ANSWER" in *'"no token"'*) ;; *) return 1 ;; esac
  tok="$(_lg_forgejo admin user generate-access-token --username "$LOCALGIT_USER" --token-name "devos-ade-code-$(date +%s)" \
    --scopes "$LOCALGIT_TOKEN_SCOPES" --raw 2>/dev/null | tail -n 1 | tr -d '\r')" || tok=''
  [ -n "$tok" ] || return 1
  msg="{\"source\":\"localgit\",\"ca\":$(_lg_json_str "$ca"),\"account\":\"$LOCALGIT_USER\",\"token\":$(_lg_json_str "$tok")}"
  tok=''
  _lg_send "$msg"; msg=''
}

# localgit_after_up — setup, ./stack up, code enable, ./stack config: the account and the Code page's host, once the container
# is healthy. Never fatal (a warning says what to do).
localgit_after_up() {
  localgit_on || return 0
  localgit_secrets
  _lg_running || { warn "the built-in git server is not running — ./stack logs forgejo says why (./stack up tries again)"; return 0; }
  localgit_ensure_admin || { warn "could not make the git server's owner account — ./stack logs forgejo"; return 0; }
  localgit_register_host || { code_ready && warn "could not connect the Code page to the built-in git server — ./stack up tries again"; }
  return 0
}

# localgit_start — setup, ./stack up and the switch: its secret and certificate, then on: the container started and healthy;
# off: removed (never touching Caddy or the gateway: setup and up bring them up with their new configuration themselves).
# Home's record of the containers follows (services_status_write). Never fatal: a container that does not start is said.
localgit_start() {
  if ! localgit_on; then localgit_remove; services_status_write; return 0; fi
  localgit_secrets
  localgit_tls_ensure || warn "the git server's certificate could not be made (openssl): the sandbox cannot reach it until ./stack up"
  run_phase "Local git server (Forgejo)" forgejo dc up -d --no-deps --wait forgejo ||
    warn "the built-in git server did not start — ./stack logs forgejo says why (Git hosts has no local server until it does)"
  services_status_write
  return 0
}

# localgit_up — ./stack config and Settings' switch: localgit_start, then Caddy and the terminal's gateway where their
# configuration changed with the switch (the site, the listener: compose recreates just those two, a few seconds), the owner
# account and the Code page's host. Never fatal.
localgit_up() {
  localgit_start
  localgit_on || { localgit_recreate_fronts; return 0; }
  localgit_recreate_fronts
  localgit_after_up
  services_status_write
  return 0
}

# localgit_recreate_fronts — Caddy and the terminal's gateway recreated where the git server's site and listener changed
localgit_recreate_fronts() {
  local s=caddy
  ! terminal_ready || s="$s terminal-gateway"
  # shellcheck disable=SC2086  # a word a service
  up_services --no-deps $s >/dev/null 2>&1 || warn "Caddy or the terminal's gateway did not restart for the git server — ./stack up"
  ensure_portal_reachable
}

# localgit_remove — the container removed (named with its profile on: off, compose would not see it); the gitdata volume
# stays. Only when there is one; never fatal.
localgit_remove() {
  [ -n "$(_LG_PROFILE=1 dc ps -aq forgejo 2>/dev/null)" ] || return 0
  _LG_PROFILE=1 dc rm -sf forgejo >/dev/null 2>&1 || warn "could not remove the git server's container — ./stack down removes it"
}

# localgit_rollback_cleanup — ./stack rollback to a version without it: the container removed by its Compose labels (the
# repositories' volume stays; the network goes after the up, lib/rollback.sh)
localgit_rollback_cleanup() {
  local p ids
  p="$(project_name)"
  ids="$(docker ps -aq --filter "label=com.docker.compose.project=$p" --filter "label=com.docker.compose.service=forgejo" 2>/dev/null || true)"
  # shellcheck disable=SC2086  # one id per word
  [ -z "$ids" ] || docker rm -f $ids >/dev/null 2>&1 || warn "could not remove the git server's container — remove it with: docker rm -f $p-forgejo-1"
}

# localgit_uninstall_cleanup — ./stack uninstall: the repositories' volume (and its network) removed even while the server is off
# (its profile is not on then: `dc down -v` would not see them). Never fatal.
localgit_uninstall_cleanup() {
  local p; p="$(project_name)"
  _LG_PROFILE=1 dc rm -sfv forgejo >/dev/null 2>&1 || true
  docker volume rm "${p}_gitdata" >/dev/null 2>&1 || true
  docker network rm "${p}_localgit" >/dev/null 2>&1 || true
}

# localgit_web_url -> the server's web address (http://git.PORTAL_HOST[:port])
localgit_web_url() { portal_url git; }

localgit_status_line() {
  if localgit_on; then
    printf '  Git server on (Forgejo): %s — sign in as %s (password: LOCALGIT_ADMIN_PASSWORD in .env); the Code page'"'"'s sandbox clones and pushes\n' "$(localgit_web_url)" "$LOCALGIT_USER"
    printf '             with https://%s:%s/%s/REPO.git (Git hosts: Local git server; a push creates a missing repository, private)\n' "$LOCALGIT_GATEWAY_HOST" "$LOCALGIT_GATEWAY_PORT" "$LOCALGIT_USER"
  else
    printf '  Git server off (LOCALGIT=off): ./stack config set LOCALGIT on turns the built-in git server on — its repositories stay in the gitdata volume\n'
  fi
}
localgit_summary_line() {
  localgit_on || return 0
  printf '  Git        %s (the built-in git server: repositories on this computer; sign in as %s)\n' "$(localgit_web_url)" "$LOCALGIT_USER"
}
